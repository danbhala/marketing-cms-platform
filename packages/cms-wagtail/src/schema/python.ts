import type { WagtailSchema, WagtailTypeSchema } from "./index"
import { WAGTAIL_VERSION } from "../naming"

/**
 * Renders the Python modules of the generated Django app. Each renderer takes
 * the JSON schema (not the content model) so the Python and `schema.json`
 * cannot drift from each other. Nothing here is parsed back: the test suite
 * compares the files byte for byte with the checked-in output.
 */
const header = (purpose: string) =>
  `"""
${purpose}

Generated by @platform/cms-wagtail from @platform/content-model for Wagtail ${WAGTAIL_VERSION}.
Do not edit by hand: run \`pnpm --filter @platform/cms-wagtail schema:generate\`.
"""
`

const py = (value: string) => JSON.stringify(value)
const docstring = (text: string, indent: string) => `${indent}"""${text.replace(/"""/g, '\\"\\"\\"')}"""\n`

const items = (schema: WagtailSchema) => schema.types.filter((t) => t.kind === "item")
const blocks = (schema: WagtailSchema) => schema.types.filter((t) => t.kind === "block")
const pages = (schema: WagtailSchema) => schema.types.filter((t) => t.base === "Page")
const settings = (schema: WagtailSchema) => schema.types.filter((t) => t.base === "BaseGenericSetting")

/**
 * Items that nest other items (a pricing plan holds actions) must be defined
 * after them in Python, so the item classes are emitted in dependency order.
 */
function sortedItems(schema: WagtailSchema): WagtailTypeSchema[] {
  const list = items(schema)
  const byPython = new Map(list.map((t) => [t.python, t]))
  const out: WagtailTypeSchema[] = []
  const seen = new Set<string>()
  const visit = (type: WagtailTypeSchema) => {
    if (seen.has(type.python)) return
    seen.add(type.python)
    for (const dependency of list) {
      if (dependency !== type && type.fields.some((f) => f.definition.includes(`${dependency.python}()`))) visit(byPython.get(dependency.python)!)
    }
    out.push(type)
  }
  list.forEach(visit)
  return out
}

function structBlock(type: WagtailTypeSchema): string {
  const lines = [`class ${type.python}(blocks.StructBlock):`]
  lines.push(docstring(type.description ?? type.label, "    "))
  for (const field of type.fields) lines.push(`    ${field.python} = ${field.definition}`)
  lines.push("", "    class Meta:", `        label = ${py(type.label)}`)
  return `${lines.join("\n")}\n`
}

/** Only the StructBlock classes for the given types, in the order given; what the docs' schema studio shows for a block someone is designing. */
export function renderStructBlocks(types: readonly WagtailTypeSchema[]): string {
  return types.map(structBlock).join("\n\n")
}

export function renderBlocksPy(schema: WagtailSchema): string {
  const streamChildren = blocks(schema)
  const parts: string[] = [
    header("StreamField blocks: one StructBlock per item and per block of the content model,\nand the ContentStreamBlock pages are built from."),
    `from django.core.exceptions import ValidationError
from rest_framework.fields import Field
from wagtail import blocks
from wagtail.blocks.list_block import ListValue
from wagtail.blocks.struct_block import StructBlockValidationError
from wagtail.documents.blocks import DocumentChooserBlock
from wagtail.images.blocks import ImageChooserBlock


def absolute_url(url, context=None):
    """File URLs are relative on local storage; the frontend wants an origin it can fetch."""
    request = context.get("request") if context else None
    if request is not None and url and not url.startswith(("http://", "https://")):
        return request.build_absolute_uri(url)
    return url


def image_data(image, context=None):
    """The fields the Images API exposes (title, width, height, download_url) plus alt, inlined."""
    if image is None:
        return None
    return {
        "id": image.pk,
        "title": image.title,
        "alt": image.default_alt_text,
        "width": image.width,
        "height": image.height,
        "url": absolute_url(image.file.url, context),
    }


def document_data(document, context=None):
    """The fields the Documents API exposes (title, download_url) plus the MIME type, inlined."""
    if document is None:
        return None
    return {
        "id": document.pk,
        "title": document.title,
        "url": absolute_url(document.url, context),
        "content_type": document.content_type,
    }


class ImageSerializer(Field):
    """Serializes an image foreign key on a model the same way MediaBlock serializes an image."""

    def to_representation(self, image):
        return image_data(image, self.context)


class APIImageChooserBlock(ImageChooserBlock):
    """Returns the image inline instead of its primary key (API v2 configuration guide, get_api_representation)."""

    def get_api_representation(self, value, context=None):
        return image_data(value, context)


class APIDocumentChooserBlock(DocumentChooserBlock):
    def get_api_representation(self, value, context=None):
        return document_data(value, context)


class APIPageChooserBlock(blocks.PageChooserBlock):
    """Returns the chosen page's id, title and URL so links need no second request."""

    def get_api_representation(self, value, context=None):
        if value is None:
            return None
        return {"id": value.pk, "title": value.title, "url": value.url}


class ItemListBlock(blocks.ListBlock):
    """
    A ListBlock whose API output is the stored form, {"type": "item", "value": ..., "id": ...}.
    ListBlock.get_api_representation returns bare values, which would lose the ids the
    frontend keys nested items by.
    """

    def get_api_representation(self, value, context=None):
        if value is None:
            return []
        if not isinstance(value, ListValue):
            value = ListValue(self, values=value)
        return [
            {
                "type": "item",
                "value": self.child_block.get_api_representation(child.value, context=context),
                "id": child.id,
            }
            for child in value.bound_blocks
        ]


class LinkBlock(blocks.StructBlock):
    """A page in this Wagtail, or an external URL / site path. One of the two is needed when required."""

    page = APIPageChooserBlock(required=False, label="Page")
    url = blocks.CharBlock(
        required=False,
        label="URL or path",
        help_text="External URL, mailto: address or a site path such as /pricing.",
    )

    def __init__(self, required=True, **kwargs):
        super().__init__(**kwargs)
        self.link_required = required

    def clean(self, value):
        result = super().clean(value)
        if self.link_required and not result.get("page") and not result.get("url"):
            raise StructBlockValidationError(
                block_errors={"url": ValidationError("Choose a page or enter a URL.")}
            )
        return result


class MediaBlock(blocks.StructBlock):
    """An image with alt text or, when accept allows video, a video uploaded as a document."""

    def __init__(self, required=True, accept="image", **kwargs):
        local_blocks = [
            ("image", APIImageChooserBlock(required=False, label="Image")),
            (
                "alt_text",
                blocks.CharBlock(
                    required=False,
                    label="Alt text",
                    help_text="Leave empty to use the image's description, or for decorative images.",
                ),
            ),
        ]
        if accept in ("video", "any"):
            local_blocks.append(
                (
                    "video",
                    APIDocumentChooserBlock(
                        required=False, label="Video", help_text="An uploaded video file (mp4, webm)."
                    ),
                )
            )
        super().__init__(local_blocks, **kwargs)
        self.media_required = required
        self.accept = accept

    def clean(self, value):
        result = super().clean(value)
        if self.media_required and not result.get("image") and not result.get("video"):
            raise StructBlockValidationError(
                block_errors={"image": ValidationError("Choose an image or a video.")}
            )
        return result


# Items ------------------------------------------------------------------------`,
  ]
  for (const type of sortedItems(schema)) parts.push(`\n\n${structBlock(type)}`)
  parts.push("\n\n# Blocks ----------------------------------------------------------------------\n")
  for (const type of streamChildren) parts.push(`\n\n${structBlock(type)}`)
  parts.push(`

class ContentStreamBlock(blocks.StreamBlock):
    """Every block a page can contain. The stream child names are the canonical block types in snake_case."""

${streamChildren.map((t) => `    ${t.stream} = ${t.python}()`).join("\n")}
`)
  return parts.join("")
}

function modelClass(type: WagtailTypeSchema, bases: string, decorator?: string): string {
  const lines: string[] = []
  if (decorator) lines.push(decorator)
  lines.push(`class ${type.python}(${bases}):`)
  lines.push(docstring(type.description ?? type.label, "    "))
  const own = type.fields.filter((f) => !f.core)
  for (const field of own) lines.push(`    ${field.python} = ${field.definition}`)
  if (own.length > 0) lines.push("")
  const panels = own.map((f) => `FieldPanel(${py(f.python)})`)
  if (type.base === "Page") {
    lines.push(`    content_panels = Page.content_panels + [${panels.join(", ")}]`)
    lines.push("")
    lines.push(`    api_fields = [`)
  } else {
    lines.push(`    panels = [${panels.join(", ")}]`)
    lines.push("")
    lines.push(`    api_fields = [`)
  }
  for (const field of own) {
    const serializer = field.definition.startsWith("models.ForeignKey(\"wagtailimages.Image\"") ? ", serializer=ImageSerializer()" : ""
    lines.push(`        APIField(${py(field.python)}${serializer}),`)
  }
  lines.push("    ]", "", "    class Meta:", `        verbose_name = ${py(type.label)}`)
  if (type.base === "BaseGenericSetting") lines.push(`        verbose_name_plural = ${py(type.label)}`)
  return `${lines.join("\n")}\n`
}

export function renderModelsPy(schema: WagtailSchema): string {
  const blockImports = [...new Set(schema.types.filter((t) => t.base !== "StructBlock").flatMap((t) => t.fields.flatMap((f) => [...f.definition.matchAll(/\b([A-Z][A-Za-z]+(?:Item|Section|StreamBlock))\(\)/g)].map((m) => m[1]!))))]
  const imports = ["ImageSerializer", ...blockImports].sort()
  const parts = [
    header("Page and settings models for the content model's documents."),
    `from django.db import models
from wagtail.admin.panels import FieldPanel
from wagtail.api import APIField
from wagtail.blocks import CharBlock
from wagtail.contrib.settings.models import BaseGenericSetting, register_setting
from wagtail.fields import RichTextField, StreamField
from wagtail.models import Page
from wagtail_headless_preview.models import HeadlessMixin

from .blocks import (
${imports.map((name) => `    ${name},`).join("\n")}
)
`,
  ]
  for (const type of pages(schema)) parts.push(`\n\n${modelClass(type, "HeadlessMixin, Page")}`)
  for (const type of settings(schema)) parts.push(`\n\n${modelClass(type, "BaseGenericSetting", "@register_setting(icon=\"cog\")")}`)
  return parts.join("").replace(/blocks\.CharBlock\(/g, "CharBlock(")
}

export function renderApiPy(schema: WagtailSchema): string {
  const settingsTypes = settings(schema)
  const viewsets = settingsTypes
    .map(
      (type) => `

class ${type.python}APIViewSet(BaseAPIViewSet):
    """GET /api/v2/${settingsEndpoint(type)}/ lists the single ${type.label.toLowerCase()} record with every field."""

    model = ${type.python}
    filter_backends = [FieldsFilter]
    listing_default_fields = BaseAPIViewSet.listing_default_fields + [
${type.fields
  .filter((f) => !f.core)
  .map((f) => `        ${py(f.python)},`)
  .join("\n")}
    ]
    name = ${py(settingsEndpoint(type))}
`,
    )
    .join("")
  return `${header("API v2 router: pages, images, documents, headless previews and site settings.")}
from django.contrib.contenttypes.models import ContentType
from rest_framework.response import Response
from wagtail.api.v2.filters import FieldsFilter
from wagtail.api.v2.router import WagtailAPIRouter
from wagtail.api.v2.views import BaseAPIViewSet, PagesAPIViewSet
from wagtail.documents.api.v2.views import DocumentsAPIViewSet
from wagtail.images.api.v2.views import ImagesAPIViewSet
from wagtail_headless_preview.models import PagePreview

from .models import ${settingsTypes.map((t) => t.python).join(", ")}

# "wagtailapi" is the URL namespace. Mount with path("api/v2/", api_router.urls)
# above the Wagtail page serving route in urls.py.
api_router = WagtailAPIRouter("wagtailapi")


class PagePreviewAPIViewSet(PagesAPIViewSet):
    """
    GET /api/v2/page_preview/1/?content_type=${schema.app}.contentpage&token=... returns the
    draft a Wagtail editor is previewing, serialized like the pages endpoint. From the
    wagtail-headless-preview README.
    """

    known_query_parameters = PagesAPIViewSet.known_query_parameters.union(["content_type", "token"])

    def listing_view(self, request):
        # Delegate to detail_view so both URLs serialize identically.
        self.action = "detail_view"
        return self.detail_view(request, 0)

    def detail_view(self, request, pk):
        page = self.get_object()
        serializer = self.get_serializer(page)
        return Response(serializer.data)

    def get_object(self):
        app_label, model = self.request.GET["content_type"].split(".")
        content_type = ContentType.objects.get(app_label=app_label, model=model)
        page_preview = PagePreview.objects.get(content_type=content_type, token=self.request.GET["token"])
        page = page_preview.as_page()
        if not page.pk:
            # A page that has never been saved has no pk; the API URL routing needs one.
            page.pk = 0
        return page
${viewsets}

api_router.register_endpoint("pages", PagesAPIViewSet)
api_router.register_endpoint("images", ImagesAPIViewSet)
api_router.register_endpoint("documents", DocumentsAPIViewSet)
api_router.register_endpoint("page_preview", PagePreviewAPIViewSet)
${settingsTypes.map((t) => `api_router.register_endpoint(${py(settingsEndpoint(t))}, ${t.python}APIViewSet)`).join("\n")}
`
}

/** Endpoint name of a settings model: `site_settings` → `/api/v2/site_settings/`. */
export function settingsEndpoint(type: WagtailTypeSchema): string {
  return type.name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase()
}

export function renderSignalsPy(schema: WagtailSchema): string {
  const pageTypes = pages(schema)
  const settingsTypes = settings(schema)
  return `${header("Posts signed revalidation events to the Next.js app. Wagtail has no outbound webhooks,\nso page_published / page_unpublished / post_page_move and settings saves are forwarded here.")}
import hashlib
import hmac
import json
import logging
from urllib import request as urlrequest

from django.conf import settings
from django.db.models.signals import post_save
from django.dispatch import receiver
from wagtail.signals import page_published, page_unpublished, post_page_move

from .models import ${[...pageTypes, ...settingsTypes].map((t) => t.python).join(", ")}

logger = logging.getLogger(__name__)

SIGNATURE_HEADER = "X-Wagtail-Signature"


def post_event(payload):
    """
    POST the JSON payload to PLATFORM_REVALIDATE_URL (the site's /api/revalidate) signed with
    HMAC-SHA256 over the raw body using PLATFORM_REVALIDATE_SECRET, as "sha256=<hex>" in the
    X-Wagtail-Signature header. Failures are logged, never raised: publishing must not depend
    on the frontend being up.
    """
    url = getattr(settings, "PLATFORM_REVALIDATE_URL", "")
    secret = getattr(settings, "PLATFORM_REVALIDATE_SECRET", "")
    if not url or not secret:
        return
    body = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8")
    signature = hmac.new(secret.encode("utf-8"), body, hashlib.sha256).hexdigest()
    request = urlrequest.Request(
        url,
        data=body,
        method="POST",
        headers={"Content-Type": "application/json", SIGNATURE_HEADER: f"sha256={signature}"},
    )
    try:
        urlrequest.urlopen(request, timeout=5)
    except Exception:  # noqa: BLE001
        logger.warning("platform_cms: revalidation request to %s failed", url, exc_info=True)


def page_path(page):
    """The page's path on the site, without host, or None when it belongs to no site."""
    parts = page.get_url_parts()
    return parts[2] if parts else None


def page_payload(event, page, **extra):
    return {
        "event": event,
        "id": page.pk,
        "type": f"{page._meta.app_label}.{page.specific_class.__name__}",
        "locale": page.locale.language_code,
        "path": page_path(page),
        **extra,
    }

${pageTypes
  .map(
    (type) => `
@receiver(page_published, sender=${type.python})
def on_page_published(sender, instance, **kwargs):
    post_event(page_payload("page_published", instance))


@receiver(page_unpublished, sender=${type.python})
def on_page_unpublished(sender, instance, **kwargs):
    post_event(page_payload("page_unpublished", instance))


@receiver(post_page_move, sender=${type.python})
def on_page_moved(sender, instance, instance_before, **kwargs):
    post_event(page_payload("page_moved", instance, old_path=page_path(instance_before)))
`,
  )
  .join("")}
${settingsTypes
  .map(
    (type) => `
@receiver(post_save, sender=${type.python})
def on_settings_saved(sender, instance, **kwargs):
    post_event({"event": "settings_updated", "id": instance.pk, "type": ${py(type.apiType ?? "")}})
`,
  )
  .join("")}`
}

