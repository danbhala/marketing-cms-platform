from django.contrib.contenttypes.models import ContentType
from rest_framework.response import Response
from wagtail.api.v2.filters import FieldsFilter, OrderingFilter
from wagtail.api.v2.router import WagtailAPIRouter
from wagtail.api.v2.views import BaseAPIViewSet, PagesAPIViewSet
from wagtail.documents.api.v2.views import DocumentsAPIViewSet
from wagtail.images.api.v2.views import ImagesAPIViewSet
from wagtail_headless_preview.models import PagePreview

from .models import Category, SiteSettings

# "wagtailapi" is the URL namespace. Mount with path("api/v2/", api_router.urls)
# above the Wagtail page serving route in urls.py.
api_router = WagtailAPIRouter("wagtailapi")


class PagePreviewAPIViewSet(PagesAPIViewSet):
    """
    GET /api/v2/page_preview/1/?content_type=platform_cms.contentpage&token=... returns the
    draft a Wagtail editor is previewing, serialized like the pages endpoint. From the
    wagtail-headless-preview README.
    """

    known_query_parameters = PagesAPIViewSet.known_query_parameters.union(["content_type", "token"])

    def listing_view(self, request):
        # Delegate to detail_view so both URLs serialize identically.
        self.action = "detail_view"
        return self.detail_view(request, 0)

    def detail_view(self, request, pk):
        page = self.get_object()
        serializer = self.get_serializer(page)
        return Response(serializer.data)

    def get_object(self):
        app_label, model = self.request.GET["content_type"].split(".")
        content_type = ContentType.objects.get(app_label=app_label, model=model)
        page_preview = PagePreview.objects.get(content_type=content_type, token=self.request.GET["token"])
        page = page_preview.as_page()
        if not page.pk:
            # A page that has never been saved has no pk; the API URL routing needs one.
            page.pk = 0
        return page


class SiteSettingsAPIViewSet(BaseAPIViewSet):
    """GET /api/v2/site_settings/ lists the single site settings record with every field."""

    model = SiteSettings
    filter_backends = [FieldsFilter]
    listing_default_fields = BaseAPIViewSet.listing_default_fields + [
        "site_name",
        "logo",
        "announcement_text",
        "announcement_href",
        "announcement_link_label",
        "navigation",
        "header_actions",
        "footer_columns",
        "footer_note",
        "social_links",
    ]
    name = "site_settings"


class CategoryAPIViewSet(BaseAPIViewSet):
    """
    GET /api/v2/category/ lists every category with its fields; ?slug=<slug>
    finds one. The frontend resolves listing filters (term slugs) to ids here, then filters
    pages with ?category=<id> on the pages endpoint.
    """

    model = Category
    filter_backends = [FieldsFilter, OrderingFilter]
    listing_default_fields = BaseAPIViewSet.listing_default_fields + [
        "title",
        "slug",
        "description",
    ]
    name = "category"


api_router.register_endpoint("pages", PagesAPIViewSet)
api_router.register_endpoint("images", ImagesAPIViewSet)
api_router.register_endpoint("documents", DocumentsAPIViewSet)
api_router.register_endpoint("page_preview", PagePreviewAPIViewSet)
api_router.register_endpoint("site_settings", SiteSettingsAPIViewSet)
api_router.register_endpoint("category", CategoryAPIViewSet)
