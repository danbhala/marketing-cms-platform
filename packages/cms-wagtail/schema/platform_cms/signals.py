"""
Posts signed revalidation events to the Next.js app. Wagtail has no outbound webhooks,
so page_published / page_unpublished / post_page_move and settings saves are forwarded here.

Generated by @platform/cms-wagtail from @platform/content-model for Wagtail 8.0.
Do not edit by hand: run `pnpm --filter @platform/cms-wagtail schema:generate`.
"""

import hashlib
import hmac
import json
import logging
from urllib import request as urlrequest

from django.conf import settings
from django.db.models.signals import post_save
from django.dispatch import receiver
from wagtail.signals import page_published, page_unpublished, post_page_move

from .models import ContentPage, SiteSettings

logger = logging.getLogger(__name__)

SIGNATURE_HEADER = "X-Wagtail-Signature"


def post_event(payload):
    """
    POST the JSON payload to PLATFORM_REVALIDATE_URL (the site's /api/revalidate) signed with
    HMAC-SHA256 over the raw body using PLATFORM_REVALIDATE_SECRET, as "sha256=<hex>" in the
    X-Wagtail-Signature header. Failures are logged, never raised: publishing must not depend
    on the frontend being up.
    """
    url = getattr(settings, "PLATFORM_REVALIDATE_URL", "")
    secret = getattr(settings, "PLATFORM_REVALIDATE_SECRET", "")
    if not url or not secret:
        return
    body = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8")
    signature = hmac.new(secret.encode("utf-8"), body, hashlib.sha256).hexdigest()
    request = urlrequest.Request(
        url,
        data=body,
        method="POST",
        headers={"Content-Type": "application/json", SIGNATURE_HEADER: f"sha256={signature}"},
    )
    try:
        urlrequest.urlopen(request, timeout=5)
    except Exception:  # noqa: BLE001
        logger.warning("platform_cms: revalidation request to %s failed", url, exc_info=True)


def page_path(page):
    """The page's path on the site, without host, or None when it belongs to no site."""
    parts = page.get_url_parts()
    return parts[2] if parts else None


def page_payload(event, page, **extra):
    return {
        "event": event,
        "id": page.pk,
        "type": f"{page._meta.app_label}.{page.specific_class.__name__}",
        "locale": page.locale.language_code,
        "path": page_path(page),
        **extra,
    }


@receiver(page_published, sender=ContentPage)
def on_page_published(sender, instance, **kwargs):
    post_event(page_payload("page_published", instance))


@receiver(page_unpublished, sender=ContentPage)
def on_page_unpublished(sender, instance, **kwargs):
    post_event(page_payload("page_unpublished", instance))


@receiver(post_page_move, sender=ContentPage)
def on_page_moved(sender, instance, instance_before, **kwargs):
    post_event(page_payload("page_moved", instance, old_path=page_path(instance_before)))


@receiver(post_save, sender=SiteSettings)
def on_settings_saved(sender, instance, **kwargs):
    post_event({"event": "settings_updated", "id": instance.pk, "type": "platform_cms.SiteSettings"})
