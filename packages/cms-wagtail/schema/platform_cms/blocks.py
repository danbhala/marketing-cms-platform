def absolute_url(url, context=None):
    """File URLs are relative on local storage; the frontend wants an origin it can fetch."""
    request = context.get("request") if context else None
    if request is not None and url and not url.startswith(("http://", "https://")):
        return request.build_absolute_uri(url)
    return url


def image_data(image, context=None):
    """The fields the Images API exposes (title, width, height, download_url) plus alt, inlined."""
    if image is None:
        return None
    return {
        "id": image.pk,
        "title": image.title,
        "alt": image.default_alt_text,
        "width": image.width,
        "height": image.height,
        "url": absolute_url(image.file.url, context),
    }


def document_data(document, context=None):
    """The fields the Documents API exposes (title, download_url) plus the MIME type, inlined."""
