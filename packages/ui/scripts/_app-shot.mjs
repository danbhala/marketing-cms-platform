import { chromium } from "playwright"
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" })
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } })
const page = await ctx.newPage()
await page.goto("http://localhost:3100/api/preview?secret=dev&path=/pricing&mode=edit", { waitUntil: "networkidle" })
await page.waitForSelector("[data-edit-id]")
await page.hover("[data-block='pricing'] h2")
await page.waitForTimeout(400)
await page.screenshot({ path: "/mnt/project-files/platform/screenshots/app-draft-mode-edit-overlay.png" })
await page.goto("http://localhost:3100/api/preview/exit?path=/en", { waitUntil: "networkidle" })
await page.screenshot({ path: "/mnt/project-files/platform/screenshots/app-published-home.png", fullPage: true })
await browser.close()
