import type { ContentTypeDescription } from "./index"

/**
 * Serialises the content model into the files the Optimizely tooling consumes.
 * `renderContentTypesModule` writes the SDK DSL (`contentType({...})`) so
 * `@optimizely/cms-cli config push` can register it; the JSON is the same data
 * for anything that prefers plain data (reviews, diffs, other tooling).
 */

const identifier = (key: string) => `${key}ContentType`

/** Pretty-print a value as TypeScript, turning `allowedTypes` keys into identifiers. */
function literal(value: unknown, indent: string, asIdentifier: boolean): string {
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]"
    const items = value.map((item) => {
      if (asIdentifier && typeof item === "string" && !item.startsWith("_")) return identifier(item)
      return literal(item, `${indent}  `, false)
    })
    const inline = items.join(", ")
    if (inline.length < 80 && !inline.includes("\n")) return `[${inline}]`
    return `[\n${items.map((item) => `${indent}  ${item},`).join("\n")}\n${indent}]`
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>)
    if (entries.length === 0) return "{}"
    // Small flat objects (enum options, string items) read better on one line.
    const flat = entries.every(([, v]) => v === null || typeof v !== "object")
    if (flat) {
      const inline = `{ ${entries.map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(", ")} }`
      if (inline.length < 80) return inline
    }
    const lines = entries.map(([k, v]) => `${indent}  ${k}: ${literal(v, `${indent}  `, k === "allowedTypes")},`)
    return `{\n${lines.join("\n")}\n${indent}}`
  }
  return JSON.stringify(value)
}

export function renderContentTypesModule(descriptions: ContentTypeDescription[]): string {
  const header = [
    "// Generated by `pnpm --filter @platform/cms-optimizely schema:generate`. Do not edit.",
    "// Source of truth: packages/content-model/src/definitions. Push with:",
    "//   npx @optimizely/cms-cli@latest config push optimizely.config.mjs",
    'import { contentType } from "@optimizely/cms-sdk"',
    "",
  ]
  const blocks = descriptions.map((description) => {
    const { description: comment, ...rest } = description
    const doc = comment ? `/** ${comment} */\n` : ""
    return `${doc}export const ${identifier(description.key)} = contentType(${literal(rest, "", false)})\n`
  })
  const all = `export const allContentTypes = [\n${descriptions.map((d) => `  ${identifier(d.key)},`).join("\n")}\n]\n`
  return [...header, ...blocks, all].join("\n")
}

export function renderContentTypesJson(descriptions: ContentTypeDescription[]): string {
  return `${JSON.stringify(
    descriptions.map(({ description: _description, ...rest }) => rest),
    null,
    2
  )}\n`
}

/** The CLI entry point: tells `config push` which files hold content types. */
export function renderBuildConfig(locales: readonly string[]): string {
  return [
    "// Generated by `pnpm --filter @platform/cms-optimizely schema:generate`.",
    "// Run from this directory: npx @optimizely/cms-cli@latest config push optimizely.config.mjs",
    'import { buildConfig } from "@optimizely/cms-sdk"',
    "",
    "export default buildConfig({",
    '  components: ["./content-types.ts"],',
    `  locale: ${JSON.stringify([...locales])},`,
    "  propertyGroups: [],",
    "})",
    "",
  ].join("\n")
}
